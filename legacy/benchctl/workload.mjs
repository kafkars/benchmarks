// Deterministic rendering of the exact resolved workload sealed with each run.

export function renderResolvedWorkload(workload) {
  return [
    'name = "producer-balanced-1k-diagnostic"',
    'status = "diagnostic"',
    "claim_eligible = false",
    'template = "producer-balanced-1k-diagnostic.toml"',
    `records = ${workload.records}`,
    `warmup_records = ${workload.warmup_records}`,
    "",
    "[application]",
    "producer_instances = 1",
    "callers_per_producer = 1",
    `max_outstanding_records = ${workload.max_outstanding_records}`,
    "",
    "[application_api]",
    'admission_shape = "public-batch"',
    'completion_shape = "aggregate-batch-terminal"',
    `batch_records = ${workload.batch_records}`,
    "",
    "[payload]",
    `bytes = ${workload.payload_bytes}`,
    'identity = "KFB1 plus 16-byte run ID plus 64-bit sequence"',
    "",
    "[producer]",
    'acks = "all"',
    "idempotence = true",
    'compression = "none"',
    `linger_ms = ${workload.linger_ms}`,
    `batch_records = ${workload.batch_records}`,
    `batch_bytes = ${workload.batch_bytes}`,
    `request_bytes = ${workload.request_bytes}`,
    `max_in_flight_requests_per_broker = ${workload.max_in_flight_requests_per_broker}`,
    `retry_max_replacements = ${workload.retry_max_replacements}`,
    `retry_backoff_ms = ${workload.retry_backoff_ms}`,
    'partitioning = "explicit-round-robin"',
    `warmup_serialized_partition_primer_records = ${workload.warmup_serialized_partition_primer_records}`,
    "",
    "[cluster]",
    "brokers = 3",
    `partitions = ${workload.partitions}`,
    `replication_factor = ${workload.replication_factor}`,
    `min_in_sync_replicas = ${workload.min_in_sync_replicas}`,
    "",
    "[native_request_concurrency]",
    `status = ${JSON.stringify(workload.native_request_concurrency.status)}`,
    `kafkars = ${JSON.stringify(workload.native_request_concurrency.kafkars)}`,
    `librdkafka_c = ${JSON.stringify(workload.native_request_concurrency.librdkafka_c)}`,
    "",
  ].join("\n");
}
